# shellcheck shell=bash
#
# 1Password-backed environment for this project. Sourced from `.envrc`, so
# direnv's stdlib (`log_error`, `watch_file`) is expected to be in scope — this
# file is not meant to be executed on its own. It does its work on being
# sourced, via the `op_load_env` call at the bottom.

# UUID of the 1Password account for the given email. `--account` matches on
# account UUID or sign-in URL, never on the email, so it has to be resolved.
op_account_uuid() {
  local email=$1

  op account list --format=json |
    jq -er --arg email "${email}" 'map(select(.email == $email))[0].account_uuid'
}

# Value of a single field of the item carrying the given tag. Only for values
# that are not secret — secrets are referenced, never read into the shell.
op_tagged_field() {
  local account=$1 tag=$2 field=$3 category=${4:-}

  local item
  item=$(op item list --account="${account}" --tags="${tag}" \
    ${category:+--categories="${category}"} --format=json |
    jq -er '.[0].id // empty')

  op item get "${item}" --account="${account}" --fields "${field}"
}

# `op://` reference to a field of the item carrying the given tag. Built from
# vault and item IDs so it survives renames.
op_tagged_ref() {
  local account=$1 tag=$2 field=$3 category=${4:-}

  op item list --account="${account}" --tags="${tag}" \
    ${category:+--categories="${category}"} --format=json |
    jq -er --arg field "${field}" \
      'if length == 0 then empty else "op://\(.[0].vault.id)/\(.[0].id)/\($field)" end'
}

# Like the above, but prints nothing and succeeds when the item is missing
op_optional_tagged_field() { op_tagged_field "$@" 2>/dev/null || true; }
op_optional_tagged_ref() { op_tagged_ref "$@" 2>/dev/null || true; }

# Generate the env file from the 1Password account of the current Git identity.
# Secret values are written as `op://` references, so the file itself never
# contains a secret.
op_write_env_file() {
  local file=$1
  local email account claude_profile

  if ! email=$(git config user.email); then
    log_error "no Git user.email configured"
    return 1
  fi

  if ! account=$(op_account_uuid "${email}"); then
    log_error "no 1Password account for Git identity ${email}"
    return 1
  fi

  claude_profile=$(op_optional_tagged_field "${account}" "claude/${email}" label=profile Login)

  (
    umask 077
    {
      printf '# Generated by .envrc.d/op_env.sh, do not commit. Delete to regenerate.\n'
      printf 'OP_ACCOUNT=%s\n' "${account}"
      if [[ -n "${claude_profile}" ]]; then
        printf 'CLAUDE_CONFIG_DIR=%s\n' "${HOME}/.claude-${claude_profile}"
      fi
    } >"${file}"
  )
}

# Export the variables of the env file. `OP_SERVICE_ACCOUNT_TOKEN` is never
# exported, even if added by hand: an unresolved `op://` reference there breaks
# every `op` invocation, `op run --env-file` itself included.
op_export_env_file() {
  local file=$1
  local line name value

  while IFS= read -r line || [[ -n "${line}" ]]; do
    if [[ -z "${line}" || "${line}" == '#'* || "${line}" != *=* ]]; then
      continue
    fi

    name=${line%%=*}
    value=${line#*=}

    if [[ "${name}" == OP_SERVICE_ACCOUNT_TOKEN ]]; then
      continue
    fi

    export "${name}=${value}"
  done <"${file}"
}

# The env file sits next to `.envrc`, one level up from this one. Derived from
# this file's own path rather than from `${PWD}`, because `source_env` sources
# it with the working directory changed to `.envrc.d`.
op_load_env() {
  local file
  file=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)/.env.project

  if [[ ! -e "${file}" ]]; then
    op_write_env_file "${file}"
  fi

  watch_file "${file}"
  op_export_env_file "${file}"
}

op_load_env
